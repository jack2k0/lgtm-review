import type { PromptAnalysis } from "@lgtm/core";

/** Gap between titles GETs while some of this session's own prompts are still queued. */
export const TITLES_POLL_MS = 3_000;

export const GENERATED_LABEL = "generated";

/** Tooltip on the label. The sentence itself is plain text. */
export const GENERATED_NOTE = "Generated by the local model; may be wrong";

/**
 * Title for one own prompt, or null.
 * An inherited prompt never gets one, even when the response map contains its index.
 */
export function titleForPrompt(titles: Record<string, string> | undefined, prompt: Pick<PromptAnalysis, "index" | "inheritedFrom">): string | null {
  if (prompt.inheritedFrom !== undefined) return null;
  const title = titles?.[String(prompt.index)];
  return title ? title : null;
}

/** Another request is due only while titles are on, some are unfinished, and the route reported no error. */
export function shouldPollTitles(res: { enabled: boolean; pending: number; error: string | null } | null): boolean {
  return res !== null && res.enabled && res.pending > 0 && res.error === null;
}
